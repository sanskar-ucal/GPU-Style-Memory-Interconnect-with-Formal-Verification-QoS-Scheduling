#!/usr/bin/env python3
"""Mutation-style regression check.

Each known defect is re-injected via a `define, then the full verification
stack runs against it. A healthy verification environment must:
  * pass everything on the clean design
  * flag every injected bug in at least one formal job or simulation test

Outputs a terminal table, docs/bug_matrix.md and docs/img/bug_matrix.png.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import run_tests  # noqa: E402

BUGS = {
    "BUG_FIFO_OVERFLOW":    "request queue accepts a push while full",
    "BUG_ARB_DOUBLE_GRANT": "fixed-priority 'lowest set bit' mask computed wrong",
    "BUG_RR_NO_ROTATE":     "round-robin pointer never advances",
    "BUG_R_MISROUTE":       "R data routed by live arbiter output, not burst owner",
    "BUG_HANDSHAKE_DROP":   "ARVALID dropped before ARREADY",
    "BUG_RESET_FSM":        "transaction FSM not cleared by reset",
}

FORMAL_JOBS = {  # column -> (sby file, clean task)
    "fifo":         ("fifo.sby", "prove"),
    "arbiter":      ("arbiter.sby", "prove"),
    "interconnect": ("interconnect.sby", "bmc"),
}

SIM_TESTS = ["smoke", "starvation", "qos_wrr", "qos_prio", "backpressure", "rw_hazard", "reset_mid"]


def sby_tasks(sby: str) -> set[str]:
    text = (ROOT / "formal" / sby).read_text()
    block = re.search(r"\[tasks\](.*?)\n\[", text, re.S).group(1)
    return {l.split()[0] for l in block.strip().splitlines() if l.strip()}


def run_formal(sby: str, task: str) -> dict:
    proc = subprocess.run(["sby", "-f", sby, task], cwd=ROOT / "formal", capture_output=True, text=True)
    out = proc.stdout
    status = "PASS" if "DONE (PASS" in out else "FAIL" if "DONE (FAIL" in out else "ERROR"
    prop = ""
    m = re.search(r"Assert failed in [^:]+: (\w+\.sv):(\d+)", out)
    if m:
        src = (ROOT / "rtl" / m.group(1)).read_text().splitlines()[int(m.group(2)) - 1]
        prop = f"{m.group(1)}:{m.group(2)}  " + re.sub(r"\s+", " ", src.strip())[:80]
    trace = f"formal/{Path(sby).stem}_{task}/engine_0/trace.vcd" if status == "FAIL" else ""
    return {"status": status, "prop": prop, "trace": trace}


def build_sim(bug: str | None) -> str:
    args = ["make", "-s", "sim"] + ([f"BUG={bug}"] if bug else [])
    subprocess.run(args, cwd=ROOT, check=True, capture_output=True)
    return str(ROOT / "build" / (f"sim_{bug}" if bug else "sim") / "Vmem_subsystem_top")


def evaluate(bug: str | None, skip_slow_clean: bool) -> dict:
    row = {"formal": {}, "sim": {}}
    for col, (sby, clean_task) in FORMAL_JOBS.items():
        task = clean_task if bug is None else bug.lower()
        if bug is None and skip_slow_clean and col == "interconnect":
            row["formal"][col] = {"status": "SKIP", "prop": "", "trace": ""}
        elif task in sby_tasks(sby):
            row["formal"][col] = run_formal(sby, task)
        else:
            row["formal"][col] = {"status": "n/a", "prop": "", "trace": ""}
    sim = build_sim(bug)
    for r in run_tests.run_suite(sim, SIM_TESTS + [f"random_{i:02d}" for i in range(4)], n_random=4, verbose=False):
        row["sim"][r["name"]] = r
    return row


def caught(row) -> bool:
    return any(f["status"] == "FAIL" for f in row["formal"].values()) or any(not s["pass"] for s in row["sim"].values())


def cell(ok_is_good: bool, failed: bool) -> str:
    return ("CAUGHT" if failed else "missed") if not ok_is_good else ("FAIL" if failed else "pass")


def render(results: dict) -> tuple[str, bool]:
    sim_cols = list(next(iter(results.values()))["sim"].keys())
    hdr = ["design"] + list(FORMAL_JOBS) + sim_cols
    lines = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    healthy = True
    for name, row in results.items():
        clean = name == "clean"
        cells = [f"`{name}`"]
        for col in FORMAL_JOBS:
            st = row["formal"][col]["status"]
            cells.append({"PASS": "✅" if clean else "·", "FAIL": "❌" if clean else "🔴 caught",
                          "n/a": "—", "SKIP": "(skipped)", "ERROR": "⚠️"}[st])
        for t in sim_cols:
            failed = not row["sim"][t]["pass"]
            cells.append(("❌" if failed else "✅") if clean else ("🔴 caught" if failed else "·"))
        lines.append("| " + " | ".join(cells) + " |")
        if clean:
            healthy &= all(f["status"] in ("PASS", "SKIP") for f in row["formal"].values())
            healthy &= all(s["pass"] for s in row["sim"].values())
        else:
            healthy &= caught(row)

    md = ["# Bug-injection matrix", "",
          "Generated by `make bughunt`. Each row re-injects one defect with a `` `define`` and runs the",
          "full verification stack. `🔴 caught` = that check flagged the bug; `·` = check passed (bug not",
          "visible to it). A healthy environment passes the clean design and catches every bug.", "",
          *lines, "", "## Diagnostics (first evidence per bug)", ""]
    for name, row in results.items():
        if name == "clean":
            continue
        md.append(f"### `{name}` - {BUGS[name]}")
        for col, f in row["formal"].items():
            if f["status"] == "FAIL":
                md.append(f"- **formal/{col}**: `{f['prop']}`  (counterexample: `{f['trace']}`)")
        for t, s in row["sim"].items():
            if not s["pass"]:
                md.append(f"- **sim/{t}**: {s['errors'][0] if s['errors'] else 'failed'}")
                break
        md.append("")
    return "\n".join(md), healthy


def plot(results: dict, path: Path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.colors import ListedColormap
    except ImportError:
        return
    rows = list(results)
    sim_cols = list(results[rows[0]]["sim"])
    cols = [f"formal:{c}" for c in FORMAL_JOBS] + [f"sim:{c}" for c in sim_cols]
    grid = []
    for r in rows:
        line = []
        for c in FORMAL_JOBS:
            st = results[r]["formal"][c]["status"]
            line.append(0 if st in ("n/a", "SKIP") else (2 if st == "FAIL" else 1))
        line += [2 if not results[r]["sim"][c]["pass"] else 1 for c in sim_cols]
        grid.append(line)
    plt.style.use("dark_background")
    fig, ax = plt.subplots(figsize=(13, 4.6))
    ax.imshow(grid, cmap=ListedColormap(["#2b2b2b", "#1f6f43", "#d1495b"]), vmin=0, vmax=2, aspect="auto")
    ax.set_xticks(range(len(cols)), cols, rotation=40, ha="right", fontsize=9)
    ax.set_yticks(range(len(rows)), rows, fontsize=9)
    for i, line in enumerate(grid):
        for j, v in enumerate(line):
            txt = {0: "-", 1: "pass", 2: "FAIL"}[v]
            ax.text(j, i, txt, ha="center", va="center", fontsize=8, color="white")
    ax.set_title("Bug-injection matrix: every injected defect is flagged by at least one check", fontsize=11)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--quick", action="store_true", help="skip the slow clean full-fabric BMC")
    ap.add_argument("--bugs", nargs="*", default=list(BUGS))
    a = ap.parse_args()

    results = {}
    for bug in [None] + a.bugs:
        name = bug or "clean"
        print(f"[bughunt] {name:<22}", end="", flush=True)
        results[name] = evaluate(bug, a.quick)
        row = results[name]
        f = " ".join(f"{k}={v['status']}" for k, v in row["formal"].items())
        nfail = sum(not s["pass"] for s in row["sim"].values())
        verdict = ("ok" if nfail == 0 and "FAIL" not in f else "REGRESSION") if bug is None else \
                  ("CAUGHT" if caught(row) else "MISSED")
        print(f" {f:<55} sim_fail={nfail:<2} -> {verdict}")

    md, healthy = render(results)
    (ROOT / "docs" / "img").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "bug_matrix.md").write_text(md + "\n")
    plot(results, ROOT / "docs" / "img" / "bug_matrix.png")
    print("\nwrote docs/bug_matrix.md and docs/img/bug_matrix.png")
    print("verification environment is HEALTHY" if healthy else "verification environment has GAPS")
    sys.exit(0 if healthy else 1)


if __name__ == "__main__":
    main()
